#!/usr/bin/env node
/**
 * owner-ar-sheet.mjs — ROADMAP #10: the one-sitting masri fill sheet.
 *
 * Greps the repo for OWNER-AR slots and empty Arabic literal fields and emits ONE
 * docs/owner-ar-sheet.md with file:line, the German source string, and an empty column
 * for the owner to fill in his own masri. Re-runnable (idempotent): same tree in,
 * same sheet out — regenerate after filling slots to see what's left.
 *
 * Zero-cost, offline, node built-ins only. Run: node scripts/owner-ar-sheet.mjs
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, relative, sep } from 'node:path';

const ROOT = join(import.meta.dirname, '..');
const OUT = join(ROOT, 'docs', 'owner-ar-sheet.md');

// Where fillable slots live. Tests assert emptiness (not fillable); skills/docs describe the rule.
const SCAN_DIRS = ['client/src', 'server'];
const SKIP_FILE = (p) => /\.test\.mjs$/.test(p) || !/\.(js|jsx|mjs)$/.test(p);

// A line is a slot when it carries the marker or an empty Arabic literal field.
const MARKER = /OWNER-AR/;
const EMPTY_AR = /\b(?:[a-zA-Z]+_ar|ar)\s*:\s*(?:''|"")/;
// Runtime coercions/fallbacks are not fillable slots (e.g. `String(v?.note_ar ?? '')`,
// `catch { return { de: raw, ar: '' }; }`) — the owner can't put a string there.
// youtubeId_ar is a video-ID slot (lessons.config), not masri text — wrong sheet.
const RUNTIME = /(\?\?|\?\.|String\(|catch\b|return\b|res\.json|youtubeId)/;

// Pull the German the slot translates: T(lang, '...', '') first, then de:'...', then the
// first quoted string containing letters. Falls back to the trimmed code line as context.
function germanOf(line) {
  const t = line.match(/T\(lang,\s*(['"`])((?:\\.|(?!\1).)*)\1/);
  if (t) return t[2];
  const de = line.match(/\bde\s*:\s*(['"`])((?:\\.|(?!\1).)*)\1/);
  if (de) return de[2];
  const q = [...line.matchAll(/(['"`])((?:\\.|(?!\1).)*)\1/g)]
    .map((m) => m[2]).find((s) => /[A-Za-zÄÖÜäöüß]{2,}/.test(s));
  if (q) return q;
  const code = line.trim();
  return '`' + (code.length > 110 ? code.slice(0, 107) + '…' : code) + '`';
}

function* walk(dir) {
  for (const name of readdirSync(dir)) {
    if (name === 'node_modules' || name.startsWith('.')) continue;
    const p = join(dir, name);
    if (statSync(p).isDirectory()) yield* walk(p);
    else yield p;
  }
}

const rows = new Map(); // file → [{line, de}]
for (const dir of SCAN_DIRS) {
  for (const file of walk(join(ROOT, dir))) {
    const rel = relative(ROOT, file).split(sep).join('/');
    if (SKIP_FILE(rel)) continue;
    const lines = readFileSync(file, 'utf8').split('\n');
    lines.forEach((line, i) => {
      const isSlot = MARKER.test(line) || (EMPTY_AR.test(line) && !RUNTIME.test(line));
      if (!isSlot) return;
      // Pure-comment lines that only explain the rule (no code, no German string) are noise.
      const stripped = line.trim();
      const commentOnly = /^(\/\/|\/?\*)/.test(stripped) && !EMPTY_AR.test(line);
      if (commentOnly && !/['"`][^'"`]*[A-Za-zÄÖÜäöüß]{2,}[^'"`]*['"`]/.test(stripped)) return;
      const de = germanOf(line);
      if (!/[A-Za-zÄÖÜäöüß]{2,}/.test(de)) return; // nothing to translate on this line
      if (!rows.has(rel)) rows.set(rel, []);
      rows.get(rel).push({ line: i + 1, de });
    });
  }
}

const files = [...rows.keys()].sort();
const total = files.reduce((n, f) => n + rows.get(f).length, 0);
const esc = (s) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ');

let md = `# OWNER-AR fill sheet — the one-sitting masri pass

Generated by \`node scripts/owner-ar-sheet.mjs\` — regenerate any time; filled slots
disappear from the next run once the strings land in code.

**How to fill (owner only — no one else authors masri):**
1. Write your Cairo masri in the **عربي** column. Keep \`{placeholders}\` exactly as-is.
2. Write \`-\` to say "keep German here" (technical terms with no natural Arabic stay German).
3. Rows showing a \`code line\` instead of a clean German string are bank/data slots —
   fill what's obvious, leave the rest; a session expands those per-item with you.
4. Hand the filled file back to any session: the strings get landed, gated
   (langGuard + german-check), and shipped.

**${total} slots across ${files.length} files.**

`;

for (const f of files) {
  md += `\n## ${f}\n\n| Zeile | Deutsch | عربي |\n|---|---|---|\n`;
  for (const r of rows.get(f)) md += `| ${r.line} | ${esc(r.de)} |  |\n`;
}

writeFileSync(OUT, md);
console.log(`owner-ar-sheet: ${total} slots in ${files.length} files → docs/owner-ar-sheet.md`);
